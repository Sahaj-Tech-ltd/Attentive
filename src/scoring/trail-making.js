/**
 * Get Trail Making Part A T-score estimate from time in seconds
 * @param {number} timeSeconds - Completion time in seconds
 * @param {string} ageGroup - Age group for normative lookup
 * @returns {number} T-score estimate
 */
export function getTrailATScore(timeSeconds, ageGroup = '18-29') {
    const norms = getTrailANorms(ageGroup);
    const rounded = Math.floor(timeSeconds);
    return norms[rounded] || (timeSeconds > 180 ? 25 : 60);
}

/**
 * Get Trail Making Part B T-score estimate from time in seconds
 * @param {number} timeSeconds - Completion time in seconds
 * @param {string} ageGroup - Age group for normative lookup
 * @returns {number} T-score estimate
 */
export function getTrailBTScore(timeSeconds, ageGroup = '18-29') {
    const norms = getTrailBNorms(ageGroup);
    const rounded = Math.floor(timeSeconds);
    return norms[rounded] || (timeSeconds > 180 ? 25 : 60);
}

/**
 * Interpret B-A difference
 * @param {number} diffSeconds - B time minus A time in seconds
 * @returns {Object} { label, description }
 */
export function interpretBADiff(diffSeconds) {
    for (const bracket of BA_DIFF_INTERPRETATION) {
        if (diffSeconds <= bracket.max) {
            return { label: bracket.label, description: bracket.description };
        }
    }
    return { label: 'Markedly Elevated', description: 'Markedly elevated cognitive flexibility demand' };
}

/**
 * Calculate Trail Making A & B scores
 *
 * @param {Object} trailA - { time_ms, error_count, completed }
 * @param {Object} trailB - { time_ms, error_count, completed }
 * @param {string} ageGroup - Age group for normative lookup
 * @returns {Object} { trail_a_t_score, trail_b_t_score, trail_b_minus_a_diff_ms, trail_b_minus_a_diffInterpreted }
 */
export function calculateTrailMakingScores(trailA, trailB, ageGroup = '18-29') {
    const trailATimeSec = (trailA?.time_ms ?? 0) / 1000;
    const trailBTimeSec = (trailB?.time_ms ?? 0) / 1000;

    const trailATScore = getTrailATScore(trailATimeSec, ageGroup);
    const trailBTScore = getTrailBTScore(trailBTimeSec, ageGroup);
    const diffMs = (trailB?.time_ms ?? 0) - (trailA?.time_ms ?? 0);
    const diffInterpreted = interpretBADiff(diffMs / 1000);

    return {
        trail_a_t_score: trailATScore,
        trail_b_t_score: trailBTScore,
        trail_b_minus_a_diff_ms: diffMs,
        trail_b_minus_a_diffInterpreted: diffInterpreted.label
    };
}
